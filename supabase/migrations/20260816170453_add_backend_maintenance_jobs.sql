CREATE OR REPLACE FUNCTION private.preview_backend_transient_cleanup_v1(
  p_batch_size integer DEFAULT 1000
)
RETURNS jsonb
LANGUAGE plpgsql
STABLE
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_now timestamptz := pg_catalog.now();
  v_result jsonb;
BEGIN
  IF p_batch_size < 100 OR p_batch_size > 5000 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'batch size must be between 100 and 5000';
  END IF;

  SELECT pg_catalog.jsonb_build_object(
    'commentRequests', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_comment_requests AS requests
      WHERE (requests.completed_at IS NOT NULL
          AND requests.completed_at < v_now - interval '48 hours')
         OR (requests.completed_at IS NULL
          AND requests.response IS NULL
          AND requests.created_at < v_now - interval '48 hours')
    )),
    'commentRateLimits', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_comment_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at
          + pg_catalog.make_interval(secs => buckets.window_seconds) < v_now
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
    )),
    'shareRateLimits', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_share_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at < v_now - interval '48 hours'
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
    )),
    'shareOwnerRateLimits', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_share_owner_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at < v_now - interval '48 hours'
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
    )),
    'collaborationSessions', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_comment_collaboration_sessions AS sessions
      WHERE (
        sessions.expires_at < v_now - interval '24 hours'
        OR sessions.revoked_at < v_now - interval '24 hours'
      )
        AND NOT EXISTS (
          SELECT 1
          FROM public.resume_comment_collaboration_members AS members
          WHERE members.session_id = sessions.session_id
        )
    )),
    'collaborationMembers', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.resume_comment_collaboration_members AS members
      WHERE members.expires_at < v_now - interval '24 hours'
         OR members.revoked_at < v_now - interval '24 hours'
    )),
    'aiFinalizedRequests', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM public.ai_credit_requests AS requests
      WHERE requests.state <> 'pending'
        AND requests.finalized_at < v_now - interval '180 days'
    )),
    'backendErrorEvents', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM private.backend_error_events AS events
      WHERE events.created_at < v_now - interval '7 days'
    )),
    'backendOperationMetrics', least(p_batch_size, (
      SELECT pg_catalog.count(*)::integer
      FROM private.backend_operation_metrics AS metrics
      WHERE metrics.bucket_minute < v_now - interval '30 days'
    ))
  ) INTO v_result;

  RETURN v_result;
END;
$$;

CREATE OR REPLACE FUNCTION private.cleanup_backend_transient_data_v1(
  p_batch_size integer DEFAULT 1000
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
SET lock_timeout = '2s'
SET statement_timeout = '30s'
AS $$
DECLARE
  v_started_at timestamptz := pg_catalog.clock_timestamp();
  v_now timestamptz := pg_catalog.now();
  v_enabled boolean;
  v_count integer;
  v_total integer := 0;
  v_batch_limit_hit boolean := false;
  v_counts jsonb := '{}'::jsonb;
  v_ai_request_ids uuid[];
  v_error_code text;
  v_duration integer;
BEGIN
  IF p_batch_size < 100 OR p_batch_size > 5000 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'batch size must be between 100 and 5000';
  END IF;

  SELECT config.cleanup_enabled
  INTO v_enabled
  FROM private.backend_maintenance_config AS config
  WHERE config.singleton;

  IF NOT coalesce(v_enabled, false) THEN
    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
      )::integer
    );
    INSERT INTO private.backend_maintenance_runs (
      job_name, outcome, started_at, finished_at, duration_ms
    ) VALUES (
      'transient_cleanup', 'skipped', v_started_at,
      pg_catalog.clock_timestamp(), v_duration
    );
    RETURN pg_catalog.jsonb_build_object('outcome', 'skipped', 'reason', 'disabled');
  END IF;

  IF NOT pg_catalog.pg_try_advisory_xact_lock(
    pg_catalog.hashtextextended('resume-backend-transient-cleanup-v1', 0)
  ) THEN
    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
      )::integer
    );
    INSERT INTO private.backend_maintenance_runs (
      job_name, outcome, started_at, finished_at, duration_ms
    ) VALUES (
      'transient_cleanup', 'skipped', v_started_at,
      pg_catalog.clock_timestamp(), v_duration
    );
    RETURN pg_catalog.jsonb_build_object('outcome', 'skipped', 'reason', 'already_running');
  END IF;

  BEGIN
    WITH candidates AS (
      SELECT requests.ctid
      FROM public.resume_comment_requests AS requests
      WHERE (requests.completed_at IS NOT NULL
          AND requests.completed_at < v_now - interval '48 hours')
         OR (requests.completed_at IS NULL
          AND requests.response IS NULL
          AND requests.created_at < v_now - interval '48 hours')
      ORDER BY coalesce(requests.completed_at, requests.created_at), requests.request_id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_comment_requests AS requests
    USING candidates
    WHERE requests.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('commentRequests', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT buckets.ctid
      FROM public.resume_comment_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at
          + pg_catalog.make_interval(secs => buckets.window_seconds) < v_now
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
      ORDER BY buckets.updated_at, buckets.bucket_key
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_comment_rate_limits AS buckets
    USING candidates
    WHERE buckets.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('commentRateLimits', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT buckets.ctid
      FROM public.resume_share_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at < v_now - interval '48 hours'
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
      ORDER BY buckets.updated_at, buckets.share_id, buckets.key_hash
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_share_rate_limits AS buckets
    USING candidates
    WHERE buckets.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('shareRateLimits', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT buckets.ctid
      FROM public.resume_share_owner_rate_limits AS buckets
      WHERE buckets.updated_at < v_now - interval '48 hours'
        AND buckets.window_started_at < v_now - interval '48 hours'
        AND (buckets.blocked_until IS NULL OR buckets.blocked_until < v_now)
      ORDER BY buckets.updated_at, buckets.user_id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_share_owner_rate_limits AS buckets
    USING candidates
    WHERE buckets.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('shareOwnerRateLimits', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT members.ctid
      FROM public.resume_comment_collaboration_members AS members
      WHERE members.expires_at < v_now - interval '24 hours'
         OR members.revoked_at < v_now - interval '24 hours'
      ORDER BY coalesce(members.revoked_at, members.expires_at), members.session_id, members.user_id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_comment_collaboration_members AS members
    USING candidates
    WHERE members.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('collaborationMembers', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT sessions.ctid
      FROM public.resume_comment_collaboration_sessions AS sessions
      WHERE (
        sessions.expires_at < v_now - interval '24 hours'
        OR sessions.revoked_at < v_now - interval '24 hours'
      )
        AND NOT EXISTS (
          SELECT 1
          FROM public.resume_comment_collaboration_members AS members
          WHERE members.session_id = sessions.session_id
        )
      ORDER BY coalesce(sessions.revoked_at, sessions.expires_at), sessions.session_id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM public.resume_comment_collaboration_sessions AS sessions
    USING candidates
    WHERE sessions.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('collaborationSessions', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    SELECT pg_catalog.array_agg(candidates.request_id)
    INTO v_ai_request_ids
    FROM (
      SELECT requests.request_id
      FROM public.ai_credit_requests AS requests
      WHERE requests.state <> 'pending'
        AND requests.finalized_at < v_now - interval '180 days'
      ORDER BY requests.finalized_at, requests.request_id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    ) AS candidates;

    v_count := coalesce(pg_catalog.cardinality(v_ai_request_ids), 0);
    IF v_count > 0 THEN
      INSERT INTO private.ai_usage_daily_rollups (
        quota_date,
        action,
        final_state,
        request_count,
        reserved_credits,
        debited_credits,
        prompt_tokens,
        completion_tokens,
        total_tokens
      )
      SELECT
        requests.quota_date,
        requests.action,
        requests.state,
        pg_catalog.count(*),
        pg_catalog.sum(requests.reserved_cost),
        pg_catalog.sum(requests.quota_debited),
        pg_catalog.sum(coalesce(requests.prompt_tokens, 0)),
        pg_catalog.sum(coalesce(requests.completion_tokens, 0)),
        pg_catalog.sum(coalesce(requests.total_tokens, 0))
      FROM public.ai_credit_requests AS requests
      WHERE requests.request_id = ANY(v_ai_request_ids)
      GROUP BY requests.quota_date, requests.action, requests.state
      ON CONFLICT (quota_date, action, final_state) DO UPDATE
      SET request_count = private.ai_usage_daily_rollups.request_count + EXCLUDED.request_count,
          reserved_credits = private.ai_usage_daily_rollups.reserved_credits + EXCLUDED.reserved_credits,
          debited_credits = private.ai_usage_daily_rollups.debited_credits + EXCLUDED.debited_credits,
          prompt_tokens = private.ai_usage_daily_rollups.prompt_tokens + EXCLUDED.prompt_tokens,
          completion_tokens = private.ai_usage_daily_rollups.completion_tokens + EXCLUDED.completion_tokens,
          total_tokens = private.ai_usage_daily_rollups.total_tokens + EXCLUDED.total_tokens,
          updated_at = pg_catalog.now();

      DELETE FROM public.ai_credit_requests AS requests
      WHERE requests.request_id = ANY(v_ai_request_ids);
    END IF;
    v_counts := v_counts || pg_catalog.jsonb_build_object('aiFinalizedRequests', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT events.ctid
      FROM private.backend_error_events AS events
      WHERE events.created_at < v_now - interval '7 days'
      ORDER BY events.created_at, events.id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM private.backend_error_events AS events
    USING candidates
    WHERE events.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('backendErrorEvents', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT metrics.ctid
      FROM private.backend_operation_metrics AS metrics
      WHERE metrics.bucket_minute < v_now - interval '30 days'
      ORDER BY metrics.bucket_minute
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM private.backend_operation_metrics AS metrics
    USING candidates
    WHERE metrics.ctid = candidates.ctid;
    GET DIAGNOSTICS v_count = ROW_COUNT;
    v_counts := v_counts || pg_catalog.jsonb_build_object('backendOperationMetrics', v_count);
    v_total := v_total + v_count;
    v_batch_limit_hit := v_batch_limit_hit OR v_count = p_batch_size;

    WITH candidates AS (
      SELECT runs.ctid
      FROM private.backend_maintenance_runs AS runs
      WHERE runs.created_at < v_now - interval '90 days'
      ORDER BY runs.created_at, runs.id
      LIMIT p_batch_size
      FOR UPDATE SKIP LOCKED
    )
    DELETE FROM private.backend_maintenance_runs AS runs
    USING candidates
    WHERE runs.ctid = candidates.ctid;

    DELETE FROM private.backend_alert_state AS alerts
    WHERE NOT alerts.active
      AND alerts.updated_at < v_now - interval '90 days';

    WITH candidates AS (
      SELECT details.ctid
      FROM cron.job_run_details AS details
      WHERE details.end_time < v_now - interval '7 days'
      ORDER BY details.end_time, details.runid
      LIMIT p_batch_size
    )
    DELETE FROM cron.job_run_details AS details
    USING candidates
    WHERE details.ctid = candidates.ctid;
  EXCEPTION
  WHEN lock_not_available THEN
    v_error_code := 'lock_timeout';
    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
      )::integer
    );
    INSERT INTO private.backend_maintenance_runs (
      job_name, outcome, processed_count, error_code,
      started_at, finished_at, duration_ms
    ) VALUES (
      'transient_cleanup', 'skipped', 0, v_error_code,
      v_started_at, pg_catalog.clock_timestamp(), v_duration
    );
    RETURN pg_catalog.jsonb_build_object('outcome', 'skipped', 'errorCode', v_error_code);
  WHEN query_canceled THEN
