CREATE TABLE private.backend_maintenance_config (
  singleton boolean PRIMARY KEY DEFAULT true CHECK (singleton),
  cleanup_enabled boolean NOT NULL DEFAULT false,
  edge_jobs_enabled boolean NOT NULL DEFAULT false,
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.now()
);

INSERT INTO private.backend_maintenance_config (singleton)
VALUES (true)
ON CONFLICT (singleton) DO NOTHING;

CREATE TABLE private.backend_maintenance_runs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  job_name text NOT NULL,
  outcome text NOT NULL,
  processed_count integer NOT NULL DEFAULT 0,
  batch_limit_hit boolean NOT NULL DEFAULT false,
  error_code text,
  details jsonb NOT NULL DEFAULT '{}'::jsonb,
  started_at timestamptz NOT NULL,
  finished_at timestamptz NOT NULL,
  duration_ms integer NOT NULL,
  created_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  CONSTRAINT backend_maintenance_runs_job_check
    CHECK (job_name ~ '^[a-z][a-z0-9_]{0,63}$'),
  CONSTRAINT backend_maintenance_runs_outcome_check
    CHECK (outcome IN ('queued', 'success', 'skipped', 'failed')),
  CONSTRAINT backend_maintenance_runs_count_check
    CHECK (processed_count >= 0),
  CONSTRAINT backend_maintenance_runs_error_check
    CHECK (error_code IS NULL OR error_code ~ '^[a-z][a-z0-9_]{0,63}$'),
  CONSTRAINT backend_maintenance_runs_details_check
    CHECK (pg_catalog.jsonb_typeof(details) = 'object'),
  CONSTRAINT backend_maintenance_runs_time_check
    CHECK (finished_at >= started_at AND duration_ms >= 0)
);

CREATE INDEX backend_maintenance_runs_job_created_idx
  ON private.backend_maintenance_runs (job_name, created_at DESC);
CREATE INDEX backend_maintenance_runs_failed_created_idx
  ON private.backend_maintenance_runs (created_at DESC)
  WHERE outcome = 'failed';

CREATE TABLE private.backend_edge_dispatches (
  request_id bigint PRIMARY KEY CHECK (request_id > 0),
  maintenance_run_id bigint NOT NULL UNIQUE
    REFERENCES private.backend_maintenance_runs (id) ON DELETE CASCADE,
  function_name text NOT NULL,
  state text NOT NULL DEFAULT 'queued',
  status_code integer,
  error_code text,
  dispatched_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  completed_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  CONSTRAINT backend_edge_dispatches_function_check
    CHECK (function_name IN ('github-stars-refresh', 'backend-ops-monitor')),
  CONSTRAINT backend_edge_dispatches_state_check
    CHECK (state IN ('queued', 'succeeded', 'failed')),
  CONSTRAINT backend_edge_dispatches_status_check
    CHECK (status_code IS NULL OR status_code BETWEEN 100 AND 599),
  CONSTRAINT backend_edge_dispatches_error_check
    CHECK (error_code IS NULL OR error_code ~ '^[a-z][a-z0-9_]{0,63}$'),
  CONSTRAINT backend_edge_dispatches_completion_check
    CHECK (
      (state = 'queued' AND completed_at IS NULL AND status_code IS NULL AND error_code IS NULL)
      OR (state = 'succeeded' AND completed_at IS NOT NULL
        AND status_code BETWEEN 200 AND 299 AND error_code IS NULL)
      OR (state = 'failed' AND completed_at IS NOT NULL AND error_code IS NOT NULL)
    )
);

CREATE INDEX backend_edge_dispatches_queued_idx
  ON private.backend_edge_dispatches (dispatched_at, request_id)
  WHERE state = 'queued';

CREATE TABLE private.backend_alert_state (
  alert_code text PRIMARY KEY,
  active boolean NOT NULL DEFAULT true,
  consecutive_observations integer NOT NULL DEFAULT 1,
  first_observed_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  last_observed_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  last_notified_at timestamptz,
  resolved_at timestamptz,
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  CONSTRAINT backend_alert_state_code_check
    CHECK (alert_code ~ '^[a-z][a-z0-9_]{0,63}$'),
  CONSTRAINT backend_alert_state_count_check
    CHECK (consecutive_observations >= 0),
  CONSTRAINT backend_alert_state_resolution_check
    CHECK (
      (active AND resolved_at IS NULL)
      OR (NOT active AND resolved_at IS NOT NULL)
    )
);

CREATE TABLE private.ai_usage_daily_rollups (
  quota_date date NOT NULL,
  action text NOT NULL,
  final_state text NOT NULL,
  request_count bigint NOT NULL DEFAULT 0,
  reserved_credits bigint NOT NULL DEFAULT 0,
  debited_credits bigint NOT NULL DEFAULT 0,
  prompt_tokens bigint NOT NULL DEFAULT 0,
  completion_tokens bigint NOT NULL DEFAULT 0,
  total_tokens bigint NOT NULL DEFAULT 0,
  updated_at timestamptz NOT NULL DEFAULT pg_catalog.now(),
  PRIMARY KEY (quota_date, action, final_state),
  CONSTRAINT ai_usage_daily_rollups_state_check
    CHECK (final_state IN ('settled', 'released', 'rejected')),
