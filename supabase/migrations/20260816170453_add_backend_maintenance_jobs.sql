CREATE OR REPLACE FUNCTION private.invoke_backend_edge_job_v1(
  p_function_name text
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
SET statement_timeout = '15s'
AS $$
DECLARE
  v_started_at timestamptz := pg_catalog.clock_timestamp();
  v_enabled boolean;
  v_project_url text;
  v_maintenance_token text;
  v_request_id bigint;
  v_duration integer;
  v_job_name text;
  v_maintenance_run_id bigint;
  v_sql_state text;
  v_error_code text;
BEGIN
  IF p_function_name NOT IN ('github-stars-refresh', 'backend-ops-monitor') THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'unsupported backend edge job';
  END IF;
  v_job_name := CASE p_function_name
    WHEN 'github-stars-refresh' THEN 'github_refresh_dispatch'
    ELSE 'ops_monitor_dispatch'
  END;

  SELECT config.edge_jobs_enabled
  INTO v_enabled
  FROM private.backend_maintenance_config AS config
  WHERE config.singleton;
  IF NOT coalesce(v_enabled, false) THEN
    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
      )::integer
    );
    INSERT INTO private.backend_maintenance_runs (
      job_name, outcome, started_at, finished_at, duration_ms
    ) VALUES (
      v_job_name, 'skipped', v_started_at,
      pg_catalog.clock_timestamp(), v_duration
    );
    RETURN pg_catalog.jsonb_build_object('outcome', 'skipped', 'reason', 'disabled');
  END IF;

  BEGIN
    SELECT secrets.decrypted_secret
    INTO STRICT v_project_url
    FROM vault.decrypted_secrets AS secrets
    WHERE secrets.name = 'resume_backend_project_url';

    SELECT secrets.decrypted_secret
    INTO STRICT v_maintenance_token
    FROM vault.decrypted_secrets AS secrets
    WHERE secrets.name = 'resume_backend_maintenance_token';

    IF v_project_url !~ '^https://[a-z0-9-]+\.supabase\.co/?$'
       OR pg_catalog.length(v_maintenance_token) < 32 THEN
      RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'invalid backend edge secrets';
    END IF;

    SELECT net.http_post(
      url => pg_catalog.rtrim(v_project_url, '/') || '/functions/v1/' || p_function_name,
      body => '{}'::jsonb,
      headers => pg_catalog.jsonb_build_object(
        'Authorization', 'Bearer ' || v_maintenance_token,
        'Content-Type', 'application/json'
      ),
      timeout_milliseconds => 10000
    ) INTO v_request_id;
  EXCEPTION WHEN OTHERS THEN
    GET STACKED DIAGNOSTICS v_sql_state = RETURNED_SQLSTATE;
    v_error_code := CASE
      WHEN v_sql_state = 'P0002' THEN 'maintenance_secret_missing'
      ELSE 'edge_dispatch_failed'
    END;
    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
      )::integer
    );
    INSERT INTO private.backend_maintenance_runs (
      job_name, outcome, error_code, started_at, finished_at, duration_ms
    ) VALUES (
      v_job_name, 'failed', v_error_code, v_started_at,
      pg_catalog.clock_timestamp(), v_duration
    );
    RETURN pg_catalog.jsonb_build_object('outcome', 'failed', 'errorCode', v_error_code);
  END;

  v_duration := greatest(
    0,
    pg_catalog.round(
      extract(epoch FROM (pg_catalog.clock_timestamp() - v_started_at)) * 1000
    )::integer
  );
  INSERT INTO private.backend_maintenance_runs (
    job_name, outcome, processed_count, details,
    started_at, finished_at, duration_ms
  ) VALUES (
    v_job_name, 'queued', 0,
    pg_catalog.jsonb_build_object('requestId', v_request_id),
    v_started_at, pg_catalog.clock_timestamp(), v_duration
  ) RETURNING id INTO v_maintenance_run_id;

  INSERT INTO private.backend_edge_dispatches (
    request_id, maintenance_run_id, function_name, dispatched_at
  ) VALUES (
    v_request_id, v_maintenance_run_id, p_function_name, v_started_at
  );

  RETURN pg_catalog.jsonb_build_object('outcome', 'queued', 'requestId', v_request_id);
END;
$$;

CREATE OR REPLACE FUNCTION private.reconcile_backend_edge_dispatches_v1(
  p_limit integer DEFAULT 200
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
SET lock_timeout = '2s'
SET statement_timeout = '30s'
AS $$
DECLARE
  v_now timestamptz := pg_catalog.now();
  v_dispatch record;
  v_state text;
  v_error_code text;
  v_completed integer := 0;
  v_succeeded integer := 0;
  v_failed integer := 0;
  v_duration integer;
BEGIN
  IF p_limit < 1 OR p_limit > 1000 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'limit must be between 1 and 1000';
  END IF;

  IF NOT pg_catalog.pg_try_advisory_xact_lock(
    pg_catalog.hashtextextended('resume-backend-edge-dispatch-reconcile-v1', 0)
  ) THEN
    RETURN pg_catalog.jsonb_build_object('outcome', 'skipped', 'reason', 'already_running');
  END IF;

  FOR v_dispatch IN
    SELECT
      dispatches.request_id,
      dispatches.maintenance_run_id,
      dispatches.dispatched_at,
      responses.id AS response_id,
      responses.status_code,
      responses.timed_out,
      responses.error_msg,
      responses.created AS response_created_at,
      queued_requests.id AS queued_request_id
    FROM private.backend_edge_dispatches AS dispatches
    LEFT JOIN net._http_response AS responses
      ON responses.id = dispatches.request_id
    LEFT JOIN net.http_request_queue AS queued_requests
      ON queued_requests.id = dispatches.request_id
    WHERE dispatches.state = 'queued'
      AND (
        responses.id IS NOT NULL
        OR (
          queued_requests.id IS NULL
          AND dispatches.dispatched_at < v_now - interval '2 minutes'
        )
      )
    ORDER BY dispatches.dispatched_at, dispatches.request_id
    LIMIT p_limit
    FOR UPDATE OF dispatches SKIP LOCKED
  LOOP
    IF v_dispatch.response_id IS NULL THEN
      v_state := 'failed';
      v_error_code := 'edge_response_missing';
    ELSIF coalesce(v_dispatch.timed_out, false) THEN
      v_state := 'failed';
      v_error_code := 'edge_response_timeout';
    ELSIF v_dispatch.error_msg IS NOT NULL THEN
      v_state := 'failed';
      v_error_code := 'edge_transport_error';
    ELSIF v_dispatch.status_code BETWEEN 200 AND 299 THEN
      v_state := 'succeeded';
      v_error_code := NULL;
    ELSE
      v_state := 'failed';
      v_error_code := 'edge_http_status';
    END IF;

    UPDATE private.backend_edge_dispatches AS dispatches
    SET state = v_state,
        status_code = CASE
          WHEN v_dispatch.status_code BETWEEN 100 AND 599
            THEN v_dispatch.status_code
          ELSE NULL
        END,
        error_code = v_error_code,
        completed_at = coalesce(v_dispatch.response_created_at, v_now),
        updated_at = v_now
    WHERE dispatches.request_id = v_dispatch.request_id;

    v_duration := greatest(
      0,
      pg_catalog.round(
        extract(epoch FROM (
          coalesce(v_dispatch.response_created_at, v_now) - v_dispatch.dispatched_at
        )) * 1000
      )::integer
    );
    UPDATE private.backend_maintenance_runs AS runs
    SET outcome = CASE WHEN v_state = 'succeeded' THEN 'success' ELSE 'failed' END,
        processed_count = CASE WHEN v_state = 'succeeded' THEN 1 ELSE 0 END,
        error_code = v_error_code,
        details = pg_catalog.jsonb_build_object(
          'requestId', v_dispatch.request_id,
          'statusCode', CASE
            WHEN v_dispatch.status_code BETWEEN 100 AND 599
              THEN v_dispatch.status_code
            ELSE NULL
          END
        ),
        finished_at = coalesce(v_dispatch.response_created_at, v_now),
        duration_ms = v_duration
    WHERE runs.id = v_dispatch.maintenance_run_id;

    v_completed := v_completed + 1;
    IF v_state = 'succeeded' THEN
      v_succeeded := v_succeeded + 1;
    ELSE
      v_failed := v_failed + 1;
    END IF;
  END LOOP;

  RETURN pg_catalog.jsonb_build_object(
    'outcome', 'success',
    'processed', v_completed,
    'succeeded', v_succeeded,
    'failed', v_failed,
    'batchLimitHit', v_completed = p_limit
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.evaluate_backend_ops_alerts_v1(
  p_window_minutes integer DEFAULT 15
)
RETURNS jsonb
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_now timestamptz := pg_catalog.now();
  v_cutoff timestamptz;
  v_alerts jsonb := '[]'::jsonb;
  v_alert jsonb;
  v_codes text[] := ARRAY[]::text[];
  v_notification_codes text[] := ARRAY[]::text[];
  v_ai_failures bigint := 0;
  v_comment_total bigint := 0;
  v_comment_failures bigint := 0;
  v_comment_deadlocks bigint := 0;
  v_share_total bigint := 0;
  v_share_failures bigint := 0;
  v_maintenance_failures bigint := 0;
  v_maintenance_failure_streak boolean := false;
  v_cron_failures bigint := 0;
  v_cron_failure_streak boolean := false;
  v_stale_edge_dispatches bigint := 0;
  v_expired_pending bigint := 0;
  v_cleanup_enabled boolean := false;
  v_cleanup_backlog boolean := false;
  v_github_fetched_at timestamptz;
  v_github_failures integer;
  v_code text;
BEGIN
  IF p_window_minutes < 5 OR p_window_minutes > 1440 THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'window must be between 5 and 1440 minutes';
  END IF;
  v_cutoff := v_now - pg_catalog.make_interval(mins => p_window_minutes);

  SELECT
    coalesce(pg_catalog.sum(metrics.request_count) FILTER (
      WHERE metrics.error_code = 'quota_finalization_failed'
    ), 0)
  INTO v_ai_failures
  FROM private.backend_operation_metrics AS metrics
  WHERE metrics.bucket_minute >= v_cutoff
    AND metrics.function_name = 'llm-proxy';

  SELECT
    coalesce(pg_catalog.sum(metrics.request_count), 0),
    coalesce(pg_catalog.sum(metrics.request_count) FILTER (
      WHERE metrics.outcome = 'server_error'
         OR metrics.error_code = 'database_deadlock'
    ), 0),
    coalesce(pg_catalog.sum(metrics.request_count) FILTER (
      WHERE metrics.error_code = 'database_deadlock'
    ), 0)
  INTO v_comment_total, v_comment_failures, v_comment_deadlocks
  FROM private.backend_operation_metrics AS metrics
  WHERE metrics.bucket_minute >= v_cutoff
    AND metrics.function_name = 'resume-comments';

  SELECT
    coalesce(pg_catalog.sum(metrics.request_count), 0),
    coalesce(pg_catalog.sum(metrics.request_count) FILTER (
      WHERE metrics.outcome = 'server_error'
    ), 0)
  INTO v_share_total, v_share_failures
  FROM private.backend_operation_metrics AS metrics
  WHERE metrics.bucket_minute >= v_cutoff
    AND metrics.function_name = 'resume-share'
    AND metrics.operation = 'share_access';

  SELECT pg_catalog.count(*)
  INTO v_maintenance_failures
  FROM private.backend_maintenance_runs AS runs
  WHERE runs.created_at >= v_cutoff
    AND runs.outcome = 'failed';

  SELECT EXISTS (
    SELECT 1
    FROM (
      SELECT
        ranked.job_name,
        pg_catalog.count(*) AS observation_count,
        pg_catalog.bool_and(ranked.outcome = 'failed') AS all_failed
      FROM (
        SELECT
          runs.job_name,
          runs.outcome,
          pg_catalog.row_number() OVER (
            PARTITION BY runs.job_name
            ORDER BY runs.created_at DESC, runs.id DESC
          ) AS observation_rank
        FROM private.backend_maintenance_runs AS runs
      ) AS ranked
      WHERE ranked.observation_rank <= 3
      GROUP BY ranked.job_name
    ) AS streaks
    WHERE streaks.observation_count = 3
      AND streaks.all_failed
  ) INTO v_maintenance_failure_streak;

  SELECT pg_catalog.count(*)
  INTO v_cron_failures
  FROM cron.job_run_details AS details
  JOIN cron.job AS jobs ON jobs.jobid = details.jobid
  WHERE details.start_time >= v_cutoff
    AND details.status <> 'succeeded'
    AND jobs.jobname IN (
      'resume-backend-ai-reconcile',
      'resume-backend-edge-dispatch-reconcile',
      'resume-backend-transient-cleanup',
      'resume-backend-transient-catchup',
      'resume-backend-ops-monitor',
      'resume-github-stars-refresh'
    );

  SELECT EXISTS (
    SELECT 1
    FROM (
      SELECT
        ranked.job_name,
        pg_catalog.count(*) AS observation_count,
        pg_catalog.bool_and(ranked.status <> 'succeeded') AS all_failed
      FROM (
        SELECT
          jobs.jobname AS job_name,
          details.status,
          pg_catalog.row_number() OVER (
            PARTITION BY jobs.jobname
            ORDER BY details.start_time DESC, details.runid DESC
          ) AS observation_rank
        FROM cron.job_run_details AS details
        JOIN cron.job AS jobs ON jobs.jobid = details.jobid
        WHERE details.end_time IS NOT NULL
          AND jobs.jobname IN (
            'resume-backend-ai-reconcile',
            'resume-backend-edge-dispatch-reconcile',
            'resume-backend-transient-cleanup',
            'resume-backend-transient-catchup',
            'resume-backend-ops-monitor',
            'resume-github-stars-refresh'
          )
      ) AS ranked
      WHERE ranked.observation_rank <= 3
      GROUP BY ranked.job_name
    ) AS streaks
    WHERE streaks.observation_count = 3
      AND streaks.all_failed
  ) INTO v_cron_failure_streak;

  SELECT pg_catalog.count(*)
  INTO v_stale_edge_dispatches
  FROM private.backend_edge_dispatches AS dispatches
  WHERE dispatches.state = 'queued'
    AND dispatches.dispatched_at < v_now - interval '2 minutes';

  SELECT pg_catalog.count(*)
  INTO v_expired_pending
  FROM public.ai_credit_requests AS requests
  WHERE requests.state = 'pending'
    AND requests.expires_at < v_now - interval '5 minutes';

  SELECT config.cleanup_enabled
  INTO v_cleanup_enabled
  FROM private.backend_maintenance_config AS config
  WHERE config.singleton;

  IF v_cleanup_enabled THEN
    SELECT pg_catalog.count(*) = 3
      AND pg_catalog.bool_and(recent.outcome = 'success' AND recent.batch_limit_hit)
    INTO v_cleanup_backlog
    FROM (
      SELECT runs.outcome, runs.batch_limit_hit
      FROM private.backend_maintenance_runs AS runs
      WHERE runs.job_name = 'transient_cleanup'
      ORDER BY runs.created_at DESC, runs.id DESC
      LIMIT 3
    ) AS recent;
    v_cleanup_backlog := coalesce(v_cleanup_backlog, false);
  END IF;

  SELECT cache.fetched_at, cache.consecutive_failures
  INTO v_github_fetched_at, v_github_failures
  FROM public.github_stars AS cache
  WHERE cache.repo = '506-fetl/resume';

  IF v_ai_failures > 0 THEN
    v_alerts := v_alerts || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'code', 'ai_quota_finalization_failed', 'severity', 'critical',
      'count', v_ai_failures, 'windowMinutes', p_window_minutes
    ));
  END IF;
  IF v_comment_deadlocks > 0
     OR v_comment_failures >= 3
     OR (v_comment_total >= 20 AND v_comment_failures * 100 >= v_comment_total * 5) THEN
    v_alerts := v_alerts || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'code', 'comment_transaction_failures', 'severity', 'high',
      'count', v_comment_failures, 'deadlocks', v_comment_deadlocks,
      'total', v_comment_total, 'windowMinutes', p_window_minutes
    ));
  END IF;
  IF v_share_failures >= 3
     OR (v_share_total >= 20 AND v_share_failures * 100 >= v_share_total * 5) THEN
    v_alerts := v_alerts || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'code', 'share_read_failures', 'severity', 'high',
      'count', v_share_failures, 'total', v_share_total,
      'windowMinutes', p_window_minutes
    ));
  END IF;
  IF v_maintenance_failure_streak
     OR v_cron_failure_streak
     OR v_stale_edge_dispatches > 0
     OR v_expired_pending > 0
     OR v_cleanup_backlog THEN
    v_alerts := v_alerts || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'code', 'backend_maintenance_failure', 'severity', 'critical',
      'failedRuns', v_maintenance_failures,
      'consecutiveFailureStreak', v_maintenance_failure_streak,
      'failedCronRuns', v_cron_failures,
      'consecutiveCronFailureStreak', v_cron_failure_streak,
      'staleEdgeDispatches', v_stale_edge_dispatches,
      'expiredPendingAiRequests', v_expired_pending,
      'cleanupBacklog', v_cleanup_backlog,
      'windowMinutes', p_window_minutes
    ));
  END IF;
  IF v_github_fetched_at IS NULL
     OR v_github_fetched_at < v_now - interval '24 hours'
     OR coalesce(v_github_failures, 0) >= 3 THEN
    v_alerts := v_alerts || pg_catalog.jsonb_build_array(pg_catalog.jsonb_build_object(
      'code', 'github_cache_stale', 'severity', 'warning',
      'consecutiveFailures', coalesce(v_github_failures, 0),
      'stale', v_github_fetched_at IS NULL OR v_github_fetched_at < v_now - interval '24 hours'
    ));
  END IF;

  FOR v_alert IN SELECT value FROM pg_catalog.jsonb_array_elements(v_alerts)
  LOOP
    v_code := v_alert ->> 'code';
    v_codes := pg_catalog.array_append(v_codes, v_code);
    INSERT INTO private.backend_alert_state (
      alert_code, active, consecutive_observations,
      first_observed_at, last_observed_at, resolved_at, updated_at
    ) VALUES (
      v_code, true, 1, v_now, v_now, NULL, v_now
    )
    ON CONFLICT (alert_code) DO UPDATE
    SET active = true,
        consecutive_observations = CASE
          WHEN private.backend_alert_state.active
            THEN private.backend_alert_state.consecutive_observations + 1
          ELSE 1
        END,
        first_observed_at = CASE
          WHEN private.backend_alert_state.active
            THEN private.backend_alert_state.first_observed_at
          ELSE v_now
        END,
        last_observed_at = v_now,
        last_notified_at = CASE
          WHEN private.backend_alert_state.active
            THEN private.backend_alert_state.last_notified_at
          ELSE NULL
        END,
        resolved_at = NULL,
        updated_at = v_now;
  END LOOP;

  UPDATE private.backend_alert_state AS state
  SET active = false,
      consecutive_observations = 0,
      resolved_at = v_now,
      updated_at = v_now
  WHERE state.active
    AND NOT (state.alert_code = ANY(v_codes));

  SELECT coalesce(pg_catalog.array_agg(state.alert_code ORDER BY state.alert_code), ARRAY[]::text[])
  INTO v_notification_codes
  FROM private.backend_alert_state AS state
  WHERE state.active
    AND (state.last_notified_at IS NULL OR state.last_notified_at < v_now - interval '1 hour');

  RETURN pg_catalog.jsonb_build_object(
    'generatedAt', v_now,
    'windowMinutes', p_window_minutes,
    'alerts', v_alerts,
    'notificationCodes', pg_catalog.to_jsonb(v_notification_codes),
    'summary', pg_catalog.jsonb_build_object(
      'aiFinalizationFailures', v_ai_failures,
      'commentRequests', v_comment_total,
      'commentFailures', v_comment_failures,
      'commentDeadlocks', v_comment_deadlocks,
      'shareReads', v_share_total,
      'shareFailures', v_share_failures,
      'maintenanceFailures', v_maintenance_failures,
      'maintenanceFailureStreak', CASE WHEN v_maintenance_failure_streak THEN 1 ELSE 0 END,
      'cronFailures', v_cron_failures,
      'cronFailureStreak', CASE WHEN v_cron_failure_streak THEN 1 ELSE 0 END,
      'staleEdgeDispatches', v_stale_edge_dispatches,
      'expiredPendingAiRequests', v_expired_pending
    )
  );
END;
$$;

CREATE OR REPLACE FUNCTION public.ack_backend_alert_delivery_v1(
  p_alert_codes text[]
)
RETURNS integer
LANGUAGE plpgsql
SECURITY DEFINER
SET search_path = ''
AS $$
DECLARE
  v_updated integer;
BEGIN
  IF p_alert_codes IS NULL
     OR pg_catalog.cardinality(p_alert_codes) < 1
     OR pg_catalog.cardinality(p_alert_codes) > 32
     OR EXISTS (
       SELECT 1
       FROM pg_catalog.unnest(p_alert_codes) AS code(value)
       WHERE code.value !~ '^[a-z][a-z0-9_]{0,63}$'
     ) THEN
    RAISE EXCEPTION USING ERRCODE = '22023', MESSAGE = 'invalid alert codes';
  END IF;

  UPDATE private.backend_alert_state AS state
  SET last_notified_at = pg_catalog.now(),
      updated_at = pg_catalog.now()
  WHERE state.active
    AND state.alert_code = ANY(p_alert_codes);
  GET DIAGNOSTICS v_updated = ROW_COUNT;
  RETURN v_updated;
END;
$$;

